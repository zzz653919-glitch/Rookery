// Builds js/i18n/content.uz.js / content.ru.js (hash of English text -> translation) from scripts/i18n/content.<lang>.txt.
//   node scripts/i18n/build-content.mjs [--allow-missing]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './extract.mjs';
import { blocks } from './content-todo.mjs';
import { hashStr } from '../../js/i18n/core.js';

const allowMissing = process.argv.includes('--allow-missing');

export function parseTranslations(text) {
  const out = new Map(); let cur = null;
  for (const raw of text.split('\n')) {
    const line = raw.replace(/\r$/, '');
    if (!line.trim() || line.startsWith('#')) continue;
    const m = /^@@ (\S+)/.exec(line);
    if (m) { cur = []; out.set(m[1], cur); continue; }
    if (!cur) throw new Error('translation line before any "@@ block" header: ' + line.slice(0, 60));
    cur.push(line.replace(/^\d+\. /, ''));
  }
  return out;
}

export async function buildDictionary(lang) {
  const file = join(ROOT, `scripts/i18n/content.${lang}.txt`);
  const tr = existsSync(file) ? parseTranslations(readFileSync(file, 'utf8')) : new Map();
  const dict = {}; const problems = [];
  for (const b of await blocks()) {
    const t = tr.get(b.id);
    if (!t) { problems.push(`${lang}: block "${b.id}" is missing`); continue; }
    if (t.length !== b.strings.length) { problems.push(`${lang}: block "${b.id}" has ${t.length} lines but ${b.strings.length} strings`); continue; }
    b.strings.forEach((src, i) => {
      const h = hashStr(src); const val = t[i] === '=' ? src : t[i];
      if (dict[h] !== undefined && dict[h] !== val) problems.push(`${lang}: "${b.id}" #${i + 1} translates a repeated English text differently`);
      dict[h] = val;
    });
  }
  return { dict, problems };
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(/[\\/]/).pop())) {
  let bad = 0;
  for (const lang of ['uz', 'ru']) {
    const { dict, problems } = await buildDictionary(lang);
    problems.forEach((p) => console.log('  ' + p));
    bad += problems.length;
    if (!problems.length || allowMissing) {
      writeFileSync(join(ROOT, `js/i18n/content.${lang}.js`), `// ${lang} translations of lessons, placement test and puzzle texts, keyed by hashStr(English text).\n// GENERATED by scripts/i18n/build-content.mjs from scripts/i18n/content.${lang}.txt — edit that file.\nexport default ${JSON.stringify(dict)};\n`);
      console.log(`${lang}: ${Object.keys(dict).length} translations`);
    }
  }
  if (bad && !allowMissing) process.exit(1);
}
