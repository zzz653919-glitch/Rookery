// Builds admin/js/i18n/ui.uz.js and ui.ru.js from scripts/i18n/admin.rows.txt (English ||| Uzbek ||| Russian). Run: node scripts/i18n/build-admin.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './extract.mjs';

const rows = readFileSync(join(ROOT, 'scripts/i18n/admin.rows.txt'), 'utf8').split('\n').filter((l) => l.trim());
const dicts = { uz: {}, ru: {} };
rows.forEach((line, i) => {
  const parts = line.split(' ||| ');
  if (parts.length !== 3) throw new Error(`admin.rows.txt line ${i + 1}: expected "English ||| Uzbek ||| Russian"`);
  const [en, uz, ru] = parts;
  if (en in dicts.uz) throw new Error(`admin.rows.txt line ${i + 1}: duplicate key "${en}"`);
  // keys keep their trailing space (used in concatenated text); an empty translation is a mistake
  if (!uz.trim() || !ru.trim()) throw new Error(`admin.rows.txt line ${i + 1}: empty translation`);
  // placeholders must be identical in every language
  const ph = (s) => [...new Set(s.match(/\{\w+\}/g) || [])].sort().join();
  for (const [l, tr] of [['uz', uz], ['ru', ru]]) if (ph(en) !== ph(tr)) throw new Error(`admin.rows.txt line ${i + 1}: placeholders differ in ${l}: ${en}`);
  dicts.uz[en] = uz; dicts.ru[en] = ru;
});
mkdirSync(join(ROOT, 'admin/js/i18n'), { recursive: true });
for (const [lang, name] of [['uz', 'Uzbek (Latin)'], ['ru', 'Russian']]) {
  writeFileSync(join(ROOT, `admin/js/i18n/ui.${lang}.js`), `// ${name} translations of the admin panel. GENERATED by scripts/i18n/build-admin.mjs from scripts/i18n/admin.rows.txt — edit that file.\nexport default ` + JSON.stringify(dicts[lang], null, 1) + ';\n');
}
console.log(`${rows.length} admin strings written for uz and ru`);
