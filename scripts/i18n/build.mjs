// Builds js/i18n/ui.uz.js and ui.ru.js from the translation table scripts/i18n/ui.rows.txt
// (one row per string:  English ||| Uzbek ||| Russian).  Run:  node scripts/i18n/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './extract.mjs';

const rows = readFileSync(join(ROOT, 'scripts/i18n/ui.rows.txt'), 'utf8').split('\n').filter((l) => l.trim());
const dicts = { uz: {}, ru: {} };
const seen = new Set();
rows.forEach((line, i) => {
  const parts = line.split(' ||| ');
  if (parts.length !== 3) throw new Error(`ui.rows.txt line ${i + 1}: expected "English ||| Uzbek ||| Russian"`);
  const [en, uz, ru] = parts.map((s) => s.trim());
  if (seen.has(en)) throw new Error(`ui.rows.txt line ${i + 1}: duplicate key "${en}"`);
  seen.add(en); dicts.uz[en] = uz; dicts.ru[en] = ru;
});
const header = (l) => `// ${l} translations of the player interface. GENERATED by scripts/i18n/build.mjs from scripts/i18n/ui.rows.txt — edit that file.\n`;
for (const [lang, name] of [['uz', 'Uzbek (Latin)'], ['ru', 'Russian']]) {
  writeFileSync(join(ROOT, `js/i18n/ui.${lang}.js`), header(name) + 'export default ' + JSON.stringify(dicts[lang], null, 1) + ';\n');
}
console.log(`${rows.length} strings written for uz and ru`);
